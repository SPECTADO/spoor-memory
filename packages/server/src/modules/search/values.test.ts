import { describe, expect, it } from 'vitest'
import { differentValues, factValues } from './values.js'

// Chunk-0 texts of the spoor-bench dedupe pairs (2026-10-22): the stored item is title + "\n\n" + body.
const stored = {
  publicApi:
    'Rate limit for the public API is 600 requests per minute per API key\n\nBurst of 100 allowed; 429 includes Retry-After.',
  ios: 'Mobile app minimum supported iOS version is 16.4\n\nAndroid minimum is API 28.',
  pods: 'Kubernetes pods have CPU requests of 250m and memory limits of 1 GiB by default\n\nOverrides live in values-prod.yaml per service.',
  cookies:
    'Session cookies expire after 14 days of inactivity and are SameSite=Lax\n\nRemember-me extends to 90 days.',
  stripe:
    'Stripe webhooks are verified with the signing secret STRIPE_WHSEC\n\nUnverified webhook calls return 400 and are logged to the security channel.',
  rls: 'Use PostgreSQL row-level security for tenant isolation\n\nEvery tenant table carries tenant_id and an RLS policy; the app sets app.tenant_id per transaction.',
  thumbs:
    'Image thumbnails are generated by the resizer Lambda at 3 widths: 160, 480, 1200\n\nOriginals live in s3://larkspur-media/raw; derived files in /thumbs.',
  queues:
    'Background jobs run on BullMQ with Redis 7; the queue dashboard is at /admin/queues\n\nConcurrency 20 per worker pod.',
}

describe('factValues', () => {
  it('collects numbers, identifiers, code spans and quoted strings, lower-cased', () => {
    expect([
      ...factValues('Set `SPOOR_MODEL_DIR` to /opt/spoor/models; v1.2.3 listens on 3000, e.g. "Blue Team"'),
    ]).toEqual(expect.arrayContaining(['spoor_model_dir', '1.2.3', '3000', 'blue team', 'opt/spoor/models']))
    expect(factValues('Use e.g. server-side sessions, not JWT')).toEqual(new Set())
    expect(factValues('callers use fetchItems and the queue at 10:30')).toEqual(
      new Set(['fetchitems', '10:30']),
    )
  })
})

describe('differentValues', () => {
  it('calls same-template facts with different values different claims', () => {
    expect(
      differentValues(
        'Rate limit for the internal admin API is 60 requests per minute per user',
        stored.publicApi,
      ),
    ).toEqual({
      new: ['60'],
      existing: ['600', '100', '429'],
    })
    expect(
      differentValues(
        'Kubernetes pods for the ledger have CPU requests of 1000m and memory limits of 4 GiB',
        stored.pods,
      ),
    ).not.toBeNull()
    expect(
      differentValues(
        'Session cookies for the admin panel expire after 8 hours and are SameSite=Strict',
        stored.cookies,
      ),
    ).not.toBeNull()
  })

  it('keeps rewordings and elaborations as possible duplicates (one side a subset)', () => {
    expect(
      differentValues('Public API keys are limited to 600 requests each minute', stored.publicApi),
    ).toBeNull()
    expect(
      differentValues('iOS 16.4 is the lowest iOS version the mobile app supports', stored.ios),
    ).toBeNull()
    expect(
      differentValues('We verify Stripe webhook signatures using the STRIPE_WHSEC secret', stored.stripe),
    ).toBeNull()
    expect(
      differentValues(
        'Tenant isolation is enforced by Postgres RLS policies on every tenant table',
        stored.rls,
      ),
    ).toBeNull()
    expect(
      differentValues('The resizer Lambda produces thumbnails 160, 480 and 1200 pixels wide', stored.thumbs),
    ).toBeNull()
    expect(
      differentValues(
        'BullMQ on Redis 7 runs the background jobs; queues dashboard lives at /admin/queues',
        stored.queues,
      ),
    ).toBeNull()
    expect(differentValues('no values here', 'none there either')).toBeNull()
  })
})
